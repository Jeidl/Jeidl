def tc(frames):
    s, f = divmod(frames, FPS)
    m, s = divmod(s, 60)
    return f"{m:02d}:{s:02d}:{f:02d}"

def table(shots, total_s):
    rows = ["| 镜号 | 入点 | 时长（秒/帧） | 段落 | 景别·运镜 | 画面 | 停/爆 | 速度 | 声音 | 字幕卡 / 转场 |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    t = 0
    for i, (seg, dur, cam, pic, pb, spd, snd, card) in enumerate(shots):
        f = round(dur * FPS)
        assert abs(f - dur * FPS) < 1e-9, f"shot {i}: {dur}s is not a whole number of frames"
        rows.append(f"| {i:03d} | {tc(t)} | {dur:g} / {f} | {seg} | {cam} | {pic} | {pb} | {spd} | {snd} | {card} |")
        t += f
    assert t == total_s * FPS, f"total {t / FPS}s != {total_s}s"
    return "\n".join(rows), len(shots)

doc = pathlib.Path(__file__).with_name("trailer-storyboard.md")
text = doc.read_text(encoding="utf-8")
for name, shots, total in (("MAIN", MAIN, 120), ("VERTICAL", VERTICAL, 15)):
    body, n = table(shots, total)
    text, hits = re.subn(rf"(<!-- {name}:START -->).*?(<!-- {name}:END -->)",
                         lambda m: m.group(1) + "\n" + body + "\n" + m.group(2), text, flags=re.S)
    assert hits == 1, f"marker {name} not found"
    print(f"{name}: {n} rows, {total}s")
doc.write_text(text, encoding="utf-8")
